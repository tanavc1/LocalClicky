import CryptoKit
import XCTest
@testable import LocalBrainKit

final class InkPromptTests: XCTestCase {
    private let summary = "The user drew 1 mark while speaking: circled an area in the top right."

    func testAddendumNamesTheMarkerAndAsksForAnAnswerAboutTheArea() {
        let text = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow", hasCloseUp: false)
        XCTAssertTrue(text.contains("a yellow marker"))
        XCTAssertTrue(text.contains("answer about the marked area"))
        XCTAssertTrue(text.contains(summary))
    }

    func testCloseUpLineOnlyWhenTheSecondImageIsSent() {
        let withCrop = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow", hasCloseUp: true)
        let without = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow", hasCloseUp: false)
        XCTAssertTrue(withCrop.contains("the second image is a close-up of the marked area"))
        XCTAssertFalse(without.contains("second image"))
    }

    func testMarkerColourFollowsThePreset() {
        let red = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "red", hasCloseUp: false)
        XCTAssertTrue(red.contains("a red marker"))
        XCTAssertFalse(red.contains("yellow"))
    }

    func testAccessibilityBlockIsAddedOnlyWhenPresent() {
        let block = "Elements inside the circled area, in reading order:\n- button \"Save\""
        let with = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow",
                                            hasCloseUp: true, accessibilityBlock: block)
        XCTAssertTrue(with.hasSuffix(block))
        XCTAssertTrue(with.contains("read directly from the app itself"))
        XCTAssertTrue(with.contains("use them exactly as written"))
        let sentenceIndex = with.range(of: "read directly from the app itself")!.lowerBound
        XCTAssertLessThan(sentenceIndex, with.range(of: block)!.lowerBound)
        let empty = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow",
                                             hasCloseUp: true, accessibilityBlock: "  \n ")
        XCTAssertFalse(empty.contains("Elements inside"))
        XCTAssertFalse(empty.contains("read directly from the app"))
        XCTAssertFalse(empty.hasSuffix("\n"))
    }

    // The ink describe turn is the eval's arm A1FPC (clicky-eval ce_ink.py). The
    // expected strings below were generated by ce_ink.user_text(task, "A1FPC") and
    // INK_SYSTEM; the close-up line is the harness's CROP_NOTE, byte for byte.

    func testInkDescribeSystemPromptIsTheEvalsInkSystemByteForByte() {
        XCTAssertEqual(LocalPrompts.inkDescribe, "you are localclicky. the user marked one thing on their screen. say what that one thing is. begin with \"that's the <name>\". name the exact control, icon, row or word that is marked; use its label if it has one. do not describe the app, the window or anything else on screen. your reply is read aloud: one or two short sentences, all lowercase, no emojis, no markdown, no lists.")
        // ce_prompts.sha256(ce_ink.INK_SYSTEM), the A1FP and A1FPC pin in ce_ink.SYSTEM_SHA256.
        let digest = SHA256.hash(data: Data(LocalPrompts.inkDescribe.utf8)).map { String(format: "%02x", $0) }.joined()
        XCTAssertEqual(digest, "a8eedf21bc366a022b233733a2af1c73d04670a82a14cf7f45ddda646269ec46")
        XCTAssertFalse(LocalPrompts.inkDescribe.contains("\n"))
    }

    // The explain prompt is not a measured request; the clicky-eval check pins the same string and sha256.
    func testInkExplainPromptIsPinnedAndHasNoNamingOpenerAndNoDashes() {
        let prompt = LocalPrompts.inkExplain
        let digest = SHA256.hash(data: Data(prompt.utf8)).map { String(format: "%02x", $0) }.joined()
        XCTAssertEqual(digest, "6eb44904b41051e2a028e5f7cc6af9e5e22cd1c70b8a5ff6f1ef2bc97e1ecc85")
        XCTAssertFalse(prompt.contains("that's the"))
        XCTAssertTrue(prompt.contains("numbers as digits"))
        XCTAssertFalse(prompt.contains("\u{2014}"))
        XCTAssertFalse(prompt.contains("\u{2013}"))
        XCTAssertFalse(prompt.contains("\n"))
    }

    func testMarkLinesPerKind() {
        XCTAssertEqual(LocalPrompts.inkMarkLine(kind: .circle, hasCloseUp: true), "the marked thing is inside the ring.")
        XCTAssertEqual(LocalPrompts.inkMarkLine(kind: .line, hasCloseUp: true), "the marked thing is directly above the line.")
        XCTAssertEqual(LocalPrompts.inkMarkLine(kind: .scribble, hasCloseUp: true),
                       "the marked thing is under the scribble, so it may be hidden in the first image; the second image shows the same area without the ink.")
        XCTAssertEqual(LocalPrompts.inkMarkLine(kind: .scribble, hasCloseUp: false),
                       "the marked thing is under the scribble, so it may be hidden in the first image.")
    }

    func testInkDescribeUserTurnForACircle() {
        let turn = "what is this?\n\n" + LocalPrompts.inkAddendum(
            gestureSummary: "The user drew 1 mark while speaking: circled an area in the top left.",
            markerColourName: "yellow", hasCloseUp: true, markKind: .circle)
        XCTAssertEqual(turn, "what is this?\n\nthe user drew on the screen with a yellow marker while speaking, so they are marking an area on purpose. answer about the marked area.\nThe user drew 1 mark while speaking: circled an area in the top left.\nthe second image is a close-up of the marked area.\nthe marked thing is inside the ring.")
    }

    func testInkDescribeUserTurnForALine() {
        let turn = "what is this?\n\n" + LocalPrompts.inkAddendum(
            gestureSummary: "The user drew 1 mark while speaking: drew a short line in the left.",
            markerColourName: "yellow", hasCloseUp: true, markKind: .line)
        XCTAssertEqual(turn, "what is this?\n\nthe user drew on the screen with a yellow marker while speaking, so they are marking an area on purpose. answer about the marked area.\nThe user drew 1 mark while speaking: drew a short line in the left.\nthe second image is a close-up of the marked area.\nthe marked thing is directly above the line.")
    }

    func testInkDescribeUserTurnForAScribbleHasNoAccessibilityBlock() {
        // The describe ink turn passes no Accessibility block (the app sends "" there).
        let turn = "can you tell me what this is?\n\n" + LocalPrompts.inkAddendum(
            gestureSummary: "The user drew 1 mark while speaking: scribbled over the top left.",
            markerColourName: "yellow", hasCloseUp: true, accessibilityBlock: "", markKind: .scribble)
        XCTAssertEqual(turn, "can you tell me what this is?\n\nthe user drew on the screen with a yellow marker while speaking, so they are marking an area on purpose. answer about the marked area.\nThe user drew 1 mark while speaking: scribbled over the top left.\nthe second image is a close-up of the marked area.\nthe marked thing is under the scribble, so it may be hidden in the first image; the second image shows the same area without the ink.")
        XCTAssertFalse(turn.contains("read directly from the app itself"))
        XCTAssertFalse(turn.contains("Elements inside"))
    }

    func testInkDescribeUserTurnEqualsTheHarnessA1FPCTurnForH06a() {
        // ce_ink.user_text(all_tasks()["h06a"], "A1FPC"), question included.
        let harness = "can you tell me what this is?\n\nthe user drew on the screen with a yellow marker while speaking, so they are marking an area on purpose. answer about the marked area.\nThe user drew 1 mark while speaking: scribbled over the top left.\nthe second image is a close-up of the marked area.\nthe marked thing is under the scribble, so it may be hidden in the first image; the second image shows the same area without the ink."
        let turn = "can you tell me what this is?\n\n" + LocalPrompts.inkAddendum(
            gestureSummary: "The user drew 1 mark while speaking: scribbled over the top left.",
            markerColourName: "yellow", hasCloseUp: true, accessibilityBlock: "", markKind: .scribble)
        XCTAssertEqual(turn, harness)
    }

    func testNoMarkLineWithoutAMarkKind() {
        let text = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow", hasCloseUp: true)
        XCTAssertFalse(text.contains("the marked thing"))
    }

    func testMarkLineComesAfterTheAccessibilityBlockOnAGroundingTurn() {
        let block = "Elements inside the circled area, in reading order:\n- button \"Save\""
        let text = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow", hasCloseUp: false,
                                            accessibilityBlock: block, markKind: .circle)
        XCTAssertTrue(text.hasSuffix(block + "\nthe marked thing is inside the ring."))
    }

    func testNoEmDashesInTheAddendum() {
        let text = LocalPrompts.inkAddendum(gestureSummary: summary, markerColourName: "yellow", hasCloseUp: true)
        XCTAssertFalse(text.contains("\u{2014}"))
    }

    func testPointingPromptsAreUnchangedByTheInkWork() {
        // The addendum is appended by the caller; the system prompts stay exact.
        XCTAssertFalse(LocalPrompts.screenPointResponse(imageWidthInPixels: 1152, imageHeightInPixels: 748).contains("marker"))
        XCTAssertFalse(LocalPrompts.screenClickResponse(imageWidthInPixels: 1152, imageHeightInPixels: 748).contains("marker"))
        XCTAssertFalse(LocalPrompts.screenDescribe(imageWidthInPixels: 1152, imageHeightInPixels: 748).contains("marker"))
    }
}
